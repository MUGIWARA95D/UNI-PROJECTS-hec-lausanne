print("-"*58)

lag_results = {}
lag_names = {0:"M3(réf)",1:"M11",2:"M12",3:"M13",4:"M14",5:"M15",6:"M16",
             7:"M17b",8:"M18b",9:"M19b",10:"M20b",11:"M21b",12:"M22b"}

