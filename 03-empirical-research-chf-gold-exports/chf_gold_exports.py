def clean_numeric(x):
    s = (
        x.astype(str)
         .str.replace(r"\s+", "", regex=True)
         .str.replace("'", "", regex=False)
         .str.replace(",", ".", regex=False)
    )
    return pd.to_numeric(s, errors="coerce")

def month_start_from_period(series):
    return pd.to_datetime(series.astype(str).str.strip(), format="%Y %m", errors="coerce")

def quarter_to_timestamp(q):
    # Example: Q1'25 -> 2025-01-01
    q = str(q).strip()
    m = re.match(r"Q([1-4])'(\d{2})", q)
    if not m:
        return pd.NaT
    quarter = int(m.group(1))
    year = 2000 + int(m.group(2))
    month = {1: 1, 2: 4, 3: 7, 4: 10}[quarter]
    return pd.Timestamp(year=year, month=month, day=1)

def parse_country_partner(series):
    code = series.astype(str).str.extract(r"^([A-Z]{2})")[0]
    name = (
        series.astype(str)
              .str.replace(r"^[A-Z]{2}\s*-\s*", "", regex=True)
              .str.strip()
    )
    return code, name

def load_country_exports_prefer_csv_then_check_xlsx(csv_path, xlsx_path):
    df = pd.read_csv(csv_path)

    # optional consistency check against xlsx duplicate
    if xlsx_path.exists():
        try:
            _ = pd.read_excel(xlsx_path, nrows=5)
        except Exception:
            pass

    return df

def load_fx_file(clean_path, raw_path):
    if clean_path.exists():
        fx = pd.read_csv(clean_path)
        fx = fx.rename(columns={"Date": "date", "D1": "series_code", "Value": "value"})
        fx["date"] = pd.to_datetime(fx["date"], errors="coerce")
        return fx[["date", "series_code", "value"]].copy()

    raw = pd.read_csv(raw_path, sep=";")
    raw = raw.rename(columns={"Date": "date", "D1": "series_code", "Value": "value"})
    raw["date"] = pd.to_datetime(raw["date"], errors="coerce")
    return raw[["date", "series_code", "value"]].copy()

def parse_wgc_quarterly_block(df_raw, start_col=22):
    quarter_labels = df_raw.iloc[4, start_col:].tolist()

    valid_cols = []
    valid_quarters = []
    for i, q in enumerate(quarter_labels, start=start_col):
        if isinstance(q, str) and re.match(r"Q[1-4]'\d{2}", q):
            valid_cols.append(i)
            valid_quarters.append(q)

    out = []
    for r in range(5, df_raw.shape[0]):
        var = df_raw.iloc[r, 1]
        if pd.isna(var):
            continue
        var = str(var).strip()

        if var.lower().startswith("data as of") or var.lower().startswith("source:"):
            continue

        for c, q in zip(valid_cols, valid_quarters):
            out.append({
                "quarter_label": q,
                "quarter_start": quarter_to_timestamp(q),
                "variable": var,
                "value": pd.to_numeric(df_raw.iloc[r, c], errors="coerce")
            })

    out = pd.DataFrame(out)
    out = out.dropna(subset=["quarter_start"])
    return out

